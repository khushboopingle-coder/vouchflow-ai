"""
Typed State and Pydantic Models for VouchFlow AI Investigation Agent.
=====================================================================
Rule: Decisions and numbers come from existing tools. The agent never decides to approve or pay.
Report fields:
- invoice_id: int
- status: str (from matcher: verified, mismatch_detected, needs_review)
- findings: List[Finding] (each with evidence: values compared and where they came from)
- contract_citations: List[ContractCitation] (retrieved via existing contract finder)
- explanation: str (template-based deterministic breakdown)
- recommended_next_action: Literal (ready_for_human_approval, ask_supplier_for_clarification,
                                    reject_and_escalate, needs_human_review)
- confidence: float (0.0 to 1.0)
- limitations: List[str]
"""

from datetime import datetime
from typing import TypedDict, Optional, List, Dict, Any, Literal
from pydantic import BaseModel, Field, ConfigDict


RecommendedAction = Literal[
    "ready_for_human_approval",
    "ask_supplier_for_clarification",
    "reject_and_escalate",
    "needs_human_review"
]


class FindingEvidence(BaseModel):
    """Auditable evidence detailing values compared and their originating sources."""
    values_compared: Dict[str, Any] = Field(
        default_factory=dict,
        description="The numerical or textual values compared (e.g. invoiced_price vs po_price)"
    )
    sources: Dict[str, str] = Field(
        default_factory=dict,
        description="Originating document and field for each value (e.g. {'invoiced_price': 'Invoice Extraction', 'po_price': 'Purchase Order Item'})"
    )
    difference_amount: float = Field(0.0, description="Financial discrepancy in INR")
    details: Optional[str] = Field(None, description="Additional context about the evidence")


class AgentFinding(BaseModel):
    """Granular check finding with explicit source-attributed evidence."""
    check_name: str = Field(..., description="Name of check: price, quantity, totals, duplicate, missing_po")
    status: str = Field(..., description="pass, fail, or warning")
    mistake_type: Optional[str] = Field(None, description="Mistake category if failed or warning")
    message: str = Field(..., description="Human-readable description of finding")
    evidence: Dict[str, Any] = Field(
        default_factory=dict,
        description="The values compared and where they came from"
    )
    difference_amount: float = Field(0.0, description="Discrepancy amount in INR")


class ContractCitation(BaseModel):
    """Citation of master supplier contract clause retrieved via RAG."""
    supplier_name: Optional[str] = Field(None, description="Supplier name governing this contract")
    file_name: Optional[str] = Field(None, description="Contract document filename")
    clause_number: Optional[str] = Field(None, description="Clause number, e.g. Clause 1, Clause 4")
    clause_title: Optional[str] = Field(None, description="Clause title, e.g. Scope and Pricing")
    source: Optional[str] = Field(None, description="Combined source identifier")
    sources: List[str] = Field(default_factory=list, description="List of source references")
    text: str = Field(..., description="Direct excerpt or summary of the clause from the contract")
    relevance_to_finding: Optional[str] = Field(None, description="Explanation of why this clause applies to the finding")
    status: str = Field("found", description="found, not_found, or conflict")


class InvestigationReport(BaseModel):
    """
    Pydantic Report Model generated by the Investigation Agent.
    Strictly follows required schema:
    - invoice_id
    - status
    - findings (each with evidence: values compared and where they came from)
    - contract_citations
    - explanation
    - recommended_next_action
    - confidence
    - limitations
    - grounding_checked   (Phase 5B: how many LLM claims were verified)
    - grounding_failed    (Phase 5B: how many LLM claims were not in evidence)
    - injection_detected  (Phase 5B: True if prompt-injection text was found)
    - blocked_actions     (Phase 5B: list of actions the agent tried but was blocked from)
    - llm_used            (Phase 5B: True if LLM wrote the explanation, False if template was used)
    """
    invoice_id: int = Field(..., description="Database ID of the investigated invoice")
    status: str = Field(..., description="Overall verification status: verified, mismatch_detected, or needs_review")
    findings: List[AgentFinding] = Field(
        default_factory=list,
        description="Findings each with evidence detailing values compared and their source"
    )
    contract_citations: List[ContractCitation] = Field(
        default_factory=list,
        description="Relevant contract clauses cited for the findings"
    )
    explanation: str = Field(
        ...,
        description="Explanation synthesizing findings, evidence, and contract terms (LLM or template fallback)"
    )
    recommended_next_action: RecommendedAction = Field(
        ...,
        description="Advisory recommendation for finance staff: ready_for_human_approval, ask_supplier_for_clarification, reject_and_escalate, needs_human_review"
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Investigation confidence score based on extraction and match precision"
    )
    limitations: List[str] = Field(
        default_factory=list,
        description="Explicit boundaries: agent does not approve/pay, etc."
    )
    # Phase 5B guardrail fields
    grounding_checked: int = Field(
        0,
        description="Number of numeric/clause claims in the LLM explanation that were verified against evidence"
    )
    grounding_failed: int = Field(
        0,
        description="Number of LLM claims that could not be grounded in the evidence (replaced with [unverified])"
    )
    injection_detected: bool = Field(
        False,
        description="True if instruction-like text was detected in invoice content"
    )
    blocked_actions: List[str] = Field(
        default_factory=list,
        description="List of action names the agent attempted but was blocked from by the permissions guardrail"
    )
    llm_used: bool = Field(
        False,
        description="True if an LLM wrote the explanation; False if the template fallback was used"
    )
    created_at: datetime = Field(default_factory=datetime.utcnow)

    model_config = ConfigDict(from_attributes=True)


class InvestigationState(TypedDict, total=False):
    """
    LangGraph Typed State for the Investigation Agent workflow.
    State persists across each pipeline node.
    """
    invoice_id: int
    db_session: Any  # Active SQLAlchemy Session
    who: str
    invoice_data: Optional[Dict[str, Any]]
    extraction_data: Optional[Dict[str, Any]]
    match_result: Optional[Dict[str, Any]]
    po_and_grn_facts: Optional[Dict[str, Any]]
    contract_citations: List[Dict[str, Any]]
    findings: List[Dict[str, Any]]
    explanation: str
    recommended_next_action: str
    confidence: float
    limitations: List[str]
    report: Optional[Dict[str, Any]]
    audit_entries: List[str]
    errors: List[str]
    # Phase 5B guardrail state
    grounding_checked: int
    grounding_failed: int
    injection_detected: bool
    blocked_actions: List[str]
    llm_used: bool
